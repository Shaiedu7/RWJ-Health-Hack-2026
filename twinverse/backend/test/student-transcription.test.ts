import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {contextFromProfile} from "../lib/preview-context.js";
import type {EncounterProfile} from "../lib/patient-loader.js";
import type {Encounter,EncounterStore} from "../lib/student-encounters.js";
import {transcribeQuestion} from "../lib/student-transcription.js";
test("transcription enforces ownership, format, size and provider errors without modifying encounters",async()=>{
 process.env["ELEVENLABS_API_KEY"]="test-key";
 const context=contextFromProfile(JSON.parse(readFileSync(new URL("./fixtures/rich-wyatt-loader.json",import.meta.url),"utf8")) as EncounterProfile);
 const encounter:Encounter={encounterId:"test",patientId:context.patientId,context,mode:"development-preview",revision:0,version:0,messages:[],requests:{},updatedAt:"now"};
 const store:EncounterStore={async get(student){return student==="owner"?encounter:undefined;},async list(){return [];},async save(){throw new Error("No mutation");}};
 let calls=0;const fetcher:typeof fetch=async(_url,input)=>{calls++;assert.ok(input?.body instanceof FormData);assert.equal(input.body.get("model_id"),"scribe_v2");return Response.json({text:" Hi Wyatt, how are you? "});};
 const bytes=new Uint8Array(500);
 await assert.rejects(transcribeQuestion(store,"other","test",bytes,"audio/webm",fetcher));
 await assert.rejects(transcribeQuestion(store,"owner","test",bytes,"text/plain",fetcher));
 await assert.rejects(transcribeQuestion(store,"owner","test",new Uint8Array(2000001),"audio/webm",fetcher));assert.equal(calls,0);
 assert.equal(await transcribeQuestion(store,"owner","test",bytes,"audio/webm",fetcher),"Hi Wyatt, how are you?");
 await assert.rejects(transcribeQuestion(store,"owner","test",bytes,"audio/webm",async()=>new Response("denied",{status:401})),/permission/);
 await assert.rejects(transcribeQuestion(store,"owner","test",bytes,"audio/webm",async()=>Response.json({text:""})),/No speech/);
 assert.equal(encounter.messages.length,0);delete process.env["ELEVENLABS_API_KEY"];
});
